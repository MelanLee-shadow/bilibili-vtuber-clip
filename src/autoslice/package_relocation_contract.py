"""Field-level locator and immutability contract for package relocation.

一个在别的主机（wsl / Mac）上产完的切片包，其 JSON 文档里记的是**产它那台机
的绝对路径**。搬进 free 的交付链时只允许投影「运行期定位符」这一类字段，证据与
出处必须逐字节保持产出主机写下的值。本模块就是那条界线的机械定义：

- ``*_PATH_POINTERS``：允许被改写的定位符（白名单，按文档种类分）；
- ``_*_ROOT_ROLES``：每个定位符**必须**落在哪个根角色下（package / candidate /
  repo）。同哈希的文件在不同物理角色下仍然不可互换——例如
  ``speaker.profile`` 只能来自 repo，``speaker.speaker_override`` 只能来自
  candidate 或 repo；
- ``_*_FROZEN_PREFIXES``：冻结证据子树。这些子树里出现产出主机路径是合法的
  （它们记录的是"当时在哪台机上算的"），但**不得被改写**；
- :func:`reject_unknown_wsl_paths`：安全网。既不在定位符白名单、也不在冻结证据
  子树里的地方出现产出主机路径 → 拒绝，而不是"尽力搬"。

来源：2026-08-09 87finish 交付链在 free 上的一次性工具
``/tmp/package_relocation_contract_fasttrack_0809.py``（BV1hfuS6EENb /
BV1houS6SEF3 两条已发布件都经它落地）。当时没有上游化，于是 wsl 产的每条片都要
手工伺候；这里把它收编进仓库，供 ``scripts/import_external_package.py`` 复用。
"""

