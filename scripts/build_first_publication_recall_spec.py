#!/usr/bin/env python3
"""Create a normal same-BV recall successor from bound publication/SOURCE inputs.

No provider calls, production dispatch, registry edits, or release receipt.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.autoslice.first_publication_boundary import bind_published_recall_to_spec
from src.autoslice.new_bv_repair_authority import (
    build_new_bv_repair_authority, validate_new_bv_repair_authority,
)
from src.autoslice.source_checkpoint_parent import (
    SOURCE_ENDPOINT_DELIVERY_FIELDS, build_source_endpoint_rebuild_authority,
    binding, bound, build_source_checkpoint_parent, checkpoint_parent_paths,
    validate_source_checkpoint_parent,
)


def build_successor(*, parent_spec_path: Path, checkpoint_path: Path, output_root: Path,
                    extend_source_reserve: bool = False,
                    accept_source_endpoint: bool = False) -> dict:
    if accept_source_endpoint and extend_source_reserve:
        raise ValueError("source endpoint rebuild cannot use a witness-only extension")
    parent = bound(binding(parent_spec_path))
    cid = str(parent.get("candidate_id") or "")
    previous = validate_new_bv_repair_authority(
        parent.get("recovery_publication_authority"), candidate_id=cid,
        expected_final_title=parent.get("given_title"))
    snapshot = previous.get("review_manifest_snapshot")
    authority = build_new_bv_repair_authority(
        Path(previous["source_publication"]["path"]), candidate_id=cid,
        title=previous["title"],
        review_manifest_snapshot=Path(snapshot["path"]) if snapshot else None,
        published_recall_anchor=True)
    if accept_source_endpoint:
        authority = build_source_endpoint_rebuild_authority(parent)
    retained = build_source_checkpoint_parent(parent_spec_path=parent_spec_path,
                                               checkpoint_path=checkpoint_path,
                                               accept_source_endpoint=accept_source_endpoint)
    checkpoint = bound(retained["source_checkpoint"])
    successor = copy.deepcopy(parent)
    # These fields are generated by the verified publication bridge, never
    # supplied as an operator endpoint or a hand-signed input.
    for key in ("given_end_ms", "given_end_mode", "given_end_authority",
                "semantic_tail_trim_cap_ms"):
        successor.pop(key, None)
    successor.update(
        output_root=str(output_root),
        recovery_publication_authority=authority,
        retained_source_input=retained,
        source_text_checkpoint={"path": retained["source_checkpoint"]["path"],
                                "sha256": retained["source_checkpoint"]["sha256"]},
        existing_subtitle_surface={
            "schema_version": "existing-subtitle-surface.v1", "candidate_id": cid,
            **checkpoint["srt"],
            "source_media_sha256": checkpoint["padded"]["sha256"],
            "time_domain": "padded_local",
            "authority_kind": "PIPELINE_REVIEWED_CPA_SURFACE_NOT_HUMAN_TRUTH",
        })
    if accept_source_endpoint:
        for key in SOURCE_ENDPOINT_DELIVERY_FIELDS:
            successor.pop(key, None)
        successor["accept_source_endpoint"] = True
    else:
        bind_published_recall_to_spec(successor)
    if extend_source_reserve:
        from src.autoslice.source_witness_extension import build_plan
        successor["source_witness_extension"] = build_plan(successor)
    validate_source_checkpoint_parent(successor)
    return successor


def derive_successor_inputs(parent_spec_path: Path, *, accept_source_endpoint: bool = False) -> dict:
    """Derive every builder input from the parent spec alone (no operator choice).

    The SOURCE checkpoint is the one the parent's normal producer run wrote
    under its own output root; the successor goes to a create-only sibling
    directory named by the parent spec bytes. Nothing is written here.
    """
    import hashlib
    parent_spec_path = Path(parent_spec_path).absolute()
    raw = parent_spec_path.read_bytes()
    parent = json.loads(raw)
    cid = str(parent.get("candidate_id") or "")
    output_root = Path(str(parent.get("output_root") or ""))
    if not cid or not output_root.is_absolute():
        raise ValueError("PUBLISHED_RECALL_PARENT_SPEC_INVALID")
    checkpoint = checkpoint_parent_paths(output_root / cid, cid)["source_checkpoint"]
    if checkpoint.is_symlink() or not checkpoint.is_file():
        raise ValueError("PUBLISHED_RECALL_SOURCE_CHECKPOINT_MISSING")
    prefix = "source-endpoint-rebuild-" if accept_source_endpoint else "published-recall-"
    tag = prefix + hashlib.sha256(raw).hexdigest()[:12]
    successor_dir = output_root.parent / tag
    return {"parent_spec": parent_spec_path, "source_checkpoint": checkpoint,
            "output_root": successor_dir / "output",
            "output_spec": successor_dir / f"SPEC-{tag}.json"}


def admission_summary(spec):
    from src.autoslice.boundary_semantic_review import build_boundary_search_scope, required_source_context_end_ms
    from src.autoslice.producer_boundary import BOUNDARY_REPAIR_EXTEND_CAP_MS
    pieces = spec["pieces"]
    start = pieces[0]["start_ms"]
    available = sum(p["end_ms"] - p["start_ms"] for p in pieces)
    target = int(spec["semantic_end_ms"]) - start
    rebuilding = spec.get("accept_source_endpoint") is True
    mode = "semantic_lower_bound" if rebuilding else "published_recall_anchor"
    scope = build_boundary_search_scope(
        semantic_target_ms=target,
        published_recall_anchor_ms=None if rebuilding else spec["given_end_ms"] - start,
        boundary_end_mode=mode,
        repair_cap_ms=spec.get("boundary_repair_extend_cap_ms", BOUNDARY_REPAIR_EXTEND_CAP_MS),
        semantic_tail_trim_cap_ms=0 if rebuilding else spec["semantic_tail_trim_cap_ms"])
    # This diagnostic is not an owner freeze or semantic admission. The
    # producer still builds its complete typed required-owner/payoff contract.
    required = required_source_context_end_ms(scope)
    return {"candidate_id": spec["candidate_id"],
            "bvid": spec["recovery_publication_authority"]["bvid"],
            "published_source_end_ms": spec.get("given_end_ms"),
            "given_end_mode": mode,
            "available_source_context_ms": available,
            "minimum_required_source_context_ms": required,
            "minimum_source_reserve_deficit_ms": max(0, required - available),
            "source_checkpoint_parent": spec["retained_source_input"]["source_checkpoint"],
            "provider_calls": 0, "release_authorized": False,
            "final_media_review": "NOT_RUN_FINAL_MEDIA_DOES_NOT_EXIST"}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parent-spec", type=Path, required=True)
    parser.add_argument("--source-checkpoint", type=Path)
    parser.add_argument("--output-root", type=Path)
    parser.add_argument("--output-spec", type=Path)
    parser.add_argument("--derive-inputs", action="store_true",
                        help="derive checkpoint/output paths from the parent spec (no operator choice)")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--extend-source-reserve", action="store_true",
                        help="prepare only missing post-end witness context through the normal producer")
    modes.add_argument("--accept-source-endpoint", action="store_true",
                       help="rebuild from SOURCE without the old recut, CURRENT or publication endpoint")
    args = parser.parse_args(argv)
    if args.derive_inputs:
        if args.source_checkpoint or args.output_root or args.output_spec:
            parser.error("--derive-inputs replaces the explicit input paths")
        derived = derive_successor_inputs(args.parent_spec,
                                         accept_source_endpoint=args.accept_source_endpoint)
        args.source_checkpoint = derived["source_checkpoint"]
        args.output_root = derived["output_root"]
        args.output_spec = derived["output_spec"]
    elif not (args.source_checkpoint and args.output_root and args.output_spec):
        parser.error("--source-checkpoint, --output-root and --output-spec are required")
    if not args.output_spec.is_absolute() or not args.output_root.is_absolute():
        parser.error("outputs must be absolute")
    if args.output_root.exists() or args.output_root.is_symlink():
        parser.error("new output root must not exist")
    spec = build_successor(parent_spec_path=args.parent_spec,
                           checkpoint_path=args.source_checkpoint, output_root=args.output_root,
                           extend_source_reserve=args.extend_source_reserve,
                           accept_source_endpoint=args.accept_source_endpoint)
    summary = admission_summary(spec)
    args.output_spec.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(args.output_spec, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    with os.fdopen(fd, "w") as stream:
        json.dump(spec, stream, ensure_ascii=False, sort_keys=True, indent=2)
        stream.write("\n")
        stream.flush()
        os.fsync(stream.fileno())
    print(json.dumps({"status": "CREATED_INPUT_ONLY", "spec": binding(args.output_spec), **summary},
                     ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
